/*
 * gen-husky-render.cpp - host tool to generate husky_gpu_render.h
 *
 * Uses Mesa v11 genxml packers and cs_builder to emit exact descriptor bytes
 * and command stream words for Mali-G715 in-kernel render jobs:
 *   1. Clear job: clears 256x256 RGBA8 framebuffer to Colour A
 *   2. Triangle job: draws one Colour B triangle over Colour A background
 */
#include <cstdio>
#include <cstdlib>
#include <cstdint>
#include <vector>

#include "mali_render_build.h"

static void dump_hex_bytes(FILE *f, const char *name, const uint8_t *data, size_t size) {
    fprintf(f, "static const uint8_t %s[%zu] = {", name, size);
    for (size_t i = 0; i < size; i++) {
        fprintf(f, "%s0x%02x,", (i % 16 == 0) ? "\n\t" : " ", data[i]);
    }
    fprintf(f, "\n};\n\n");
}

static void dump_cs_words(FILE *f, const char *name, const uint64_t *words, size_t count) {
    fprintf(f, "static const uint64_t %s[%zu] = {", name, count);
    for (size_t i = 0; i < count; i++) {
        fprintf(f, "\n\t0x%016llxULL,  /* [%zu] opcode %llu */",
                (unsigned long long)words[i], i, (unsigned long long)(words[i] >> 56));
    }
    fprintf(f, "\n};\n\n");
}

int main(int argc, char **argv) {
    const char *out_path = (argc >= 2) ? argv[1] : "husky_gpu_render.h";

    FILE *f = fopen(out_path, "w");
    if (!f) {
        perror(out_path);
        return 1;
    }

    mr::ClearJobBuilt clear_job;
    if (!mr::emit_clear_job(&clear_job)) {
        fprintf(stderr, "Failed to emit clear job\n");
        fclose(f);
        return 1;
    }

    mr::TriangleJobBuilt tri_job;
    if (!mr::emit_triangle_job(&tri_job)) {
        fprintf(stderr, "Failed to emit triangle job\n");
        fclose(f);
        return 1;
    }

    fprintf(f, "/* generated by out/tools-gpu/gen-husky-render; do not edit */\n");
    fprintf(f, "/*\n");
    fprintf(f, " * Mali-G715 (Valhall CSF, arch 11) in-kernel render jobs for Pixel 8 Pro:\n");
    fprintf(f, " *   1. Clear job: fragment pass clearing 256x256 RGBA8 framebuffer to Colour A.\n");
    fprintf(f, " *   2. Triangle job: IDVS pass-through vertex shader + solid Colour B fragment shader\n");
    fprintf(f, " *      + tiler heap + fragment pass yielding Colour B triangle over Colour A.\n");
    fprintf(f, " */\n");
    fprintf(f, "#ifndef HUSKY_GPU_RENDER_H\n");
    fprintf(f, "#define HUSKY_GPU_RENDER_H\n\n");
    fprintf(f, "#include <stdint.h>\n\n");

    // Memory Addresses
    fprintf(f, "/* Fixed GPU Address Map (PACKAGE.md) */\n");
    fprintf(f, "#define HUSKY_GPU_EXEC_VA         0x%08llxu  /* 64 KiB executable, read-only */\n",
            (unsigned long long)mr::GPU_EXEC_VA);
    fprintf(f, "#define HUSKY_GPU_DESC_VA         0x%08llxu  /* Descriptors, vertex buffers, RW */\n",
            (unsigned long long)mr::GPU_DESC_VA);
    fprintf(f, "#define HUSKY_GPU_GEOM_VA         0x%08llxu  /* 64 KiB geometry buffer */\n",
            (unsigned long long)mr::GPU_GEOM_VA);
    fprintf(f, "#define HUSKY_GPU_HEAP_VA         0x%08llxu  /* 1 MiB tiler heap chunk */\n",
            (unsigned long long)mr::GPU_HEAP_VA);
    fprintf(f, "#define HUSKY_GPU_FB_VA           0x%08llxu  /* 256 KiB framebuffer linear RGBA8 */\n\n",
            (unsigned long long)mr::GPU_FB_VA);

    // Framebuffer Dimensions
    fprintf(f, "/* Framebuffer Specifications */\n");
    fprintf(f, "#define HUSKY_FB_WIDTH            %uu\n", mr::FB_WIDTH);
    fprintf(f, "#define HUSKY_FB_HEIGHT           %uu\n", mr::FB_HEIGHT);
    fprintf(f, "#define HUSKY_FB_STRIDE           %uu\n", mr::FB_STRIDE);
    fprintf(f, "#define HUSKY_FB_BYTES            %uu\n", mr::FB_BYTES);
    fprintf(f, "#define HUSKY_TILER_HEAP_SIZE     0x%08xu\n", mr::TILER_HEAP_SIZE);
    fprintf(f, "#define HUSKY_GEOM_BUF_SIZE       0x%08xu\n\n", mr::GEOM_BUF_SIZE);

    // Expected Colours
    fprintf(f, "/* Framebuffer Expected Colours */\n");
    fprintf(f, "/* Colour A (Clear): Deep Blue (R=0x%02x, G=0x%02x, B=0x%02x, A=0x%02x) */\n",
            mr::COLOR_A_R, mr::COLOR_A_G, mr::COLOR_A_B, mr::COLOR_A_A);
    fprintf(f, "#define HUSKY_COLOR_A_R           0x%02xu\n", mr::COLOR_A_R);
    fprintf(f, "#define HUSKY_COLOR_A_G           0x%02xu\n", mr::COLOR_A_G);
    fprintf(f, "#define HUSKY_COLOR_A_B           0x%02xu\n", mr::COLOR_A_B);
    fprintf(f, "#define HUSKY_COLOR_A_A           0x%02xu\n", mr::COLOR_A_A);
    fprintf(f, "#define HUSKY_COLOR_A_PACKED      0x%08xu\n\n", mr::COLOR_A_PACKED);

    fprintf(f, "/* Colour B (Triangle): Coral / Orange (R=0x%02x, G=0x%02x, B=0x%02x, A=0x%02x) */\n",
            mr::COLOR_B_R, mr::COLOR_B_G, mr::COLOR_B_B, mr::COLOR_B_A);
    fprintf(f, "#define HUSKY_COLOR_B_R           0x%02xu\n", mr::COLOR_B_R);
    fprintf(f, "#define HUSKY_COLOR_B_G           0x%02xu\n", mr::COLOR_B_G);
    fprintf(f, "#define HUSKY_COLOR_B_B           0x%02xu\n", mr::COLOR_B_B);
    fprintf(f, "#define HUSKY_COLOR_B_A           0x%02xu\n", mr::COLOR_B_A);
    fprintf(f, "#define HUSKY_COLOR_B_PACKED      0x%08xu\n\n", mr::COLOR_B_PACKED);

    // Job 1: Clear Job
    fprintf(f, "/* =================================================================== */\n");
    fprintf(f, "/* Clear Job: clears framebuffer to Colour A                           */\n");
    fprintf(f, "/* =================================================================== */\n");
    fprintf(f, "#define HUSKY_CLEAR_EXEC_VA       0x%08llxu\n", (unsigned long long)mr::GPU_EXEC_VA);
    fprintf(f, "#define HUSKY_CLEAR_EXEC_BYTES    %zuu\n", clear_job.exec_page.size());
    fprintf(f, "#define HUSKY_CLEAR_RW_VA         0x%08llxu\n", (unsigned long long)mr::GPU_DESC_VA);
    fprintf(f, "#define HUSKY_CLEAR_RW_BYTES      %zuu\n", clear_job.rw_page.size());
    fprintf(f, "#define HUSKY_CLEAR_CS_NUM_INSTR  %zuu\n\n", clear_job.cs_words.size());

    dump_hex_bytes(f, "husky_clear_exec_bytes", clear_job.exec_page.data(), clear_job.exec_page.size());
    dump_hex_bytes(f, "husky_clear_rw_bytes", clear_job.rw_page.data(), clear_job.rw_page.size());
    dump_cs_words(f, "husky_clear_cs", clear_job.cs_words.data(), clear_job.cs_words.size());

    // Job 2: Triangle Job
    fprintf(f, "/* =================================================================== */\n");
    fprintf(f, "/* Triangle Job: renders Colour B triangle over Colour A               */\n");
    fprintf(f, "/* =================================================================== */\n");
    fprintf(f, "#define HUSKY_TRI_EXEC_VA         0x%08llxu\n", (unsigned long long)mr::GPU_EXEC_VA);
    fprintf(f, "#define HUSKY_TRI_EXEC_BYTES      %zuu\n", tri_job.exec_page.size());
    fprintf(f, "#define HUSKY_TRI_RW_VA           0x%08llxu\n", (unsigned long long)mr::GPU_DESC_VA);
    fprintf(f, "#define HUSKY_TRI_RW_BYTES        %zuu\n", tri_job.rw_page.size());
    fprintf(f, "#define HUSKY_TRI_CS_NUM_INSTR    %zuu\n\n", tri_job.cs_words.size());

    dump_hex_bytes(f, "husky_tri_exec_bytes", tri_job.exec_page.data(), tri_job.exec_page.size());
    dump_hex_bytes(f, "husky_tri_rw_bytes", tri_job.rw_page.data(), tri_job.rw_page.size());
    dump_cs_words(f, "husky_tri_cs", tri_job.cs_words.data(), tri_job.cs_words.size());

    fprintf(f, "#endif /* HUSKY_GPU_RENDER_H */\n");
    fclose(f);

    printf("Generated %s successfully:\n", out_path);
    printf("  Clear Job: %zu CS words, %zu exec bytes, %zu RW bytes\n",
           clear_job.cs_words.size(), clear_job.exec_page.size(), clear_job.rw_page.size());
    printf("  Triangle Job: %zu CS words, %zu exec bytes, %zu RW bytes\n",
           tri_job.cs_words.size(), tri_job.exec_page.size(), tri_job.rw_page.size());

    return 0;
}

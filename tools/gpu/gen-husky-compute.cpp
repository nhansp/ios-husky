/*
 * gen-husky-compute: build husky_gpu.c's in-kernel compute smoke job on the host and write it as a C
 * header (bsd/dev/husky_gpu_compute.h in the xnu clone).
 *
 *   gen-husky-compute OUT.h
 *
 * The kernel runs this job on CSG0/CS0 right after its store job (xnu 0098, huskygpu=4): one
 * GPU-executable page holds the FAU, the mul_add shader, the TSD and the SPD; the compute CS
 * instructions are appended to the kernel's ring. Everything sits at fixed GPU addresses in the
 * kernel's job area (husky_gpu.c TEST_VA), so the kernel only copies bytes. Mesa's genxml packers
 * and cs_builder (MIT, used as a library at build time) encode the descriptors and instructions;
 * mali_compute_build.h is the host-tested recipe (tests/host/test_compute_job).
 *
 * Build: see tools/gpu/Makefile (needs a Mesa checkout, MESA_SRC).
 */
#include "mali_compute_build.h"
#include "mul_add_kernel.h"
#include "imul_probe_kernel.h"
#include "i128_probe_kernel.h"

#include <cstdio>
#include <cstdlib>
#include <vector>

/* Must match husky_gpu.c: TEST_VA + COMP_JOB / COMP_IN / COMP_OUT / PROBE_JOB / PROBE_OUT. */
static const uint64_t TEST_VA = 0x06000000;
static const uint64_t JOB_VA = TEST_VA + 0x4000;
static const uint64_t IN_VA = TEST_VA + 0x5000;
static const uint64_t OUT_VA = TEST_VA + 0x6000;
static const uint64_t PROBE_JOB_VA = TEST_VA + 0x8000;
static const uint64_t PROBE_OUT_VA = TEST_VA + 0x9000;    /* 5 arrays of 1 KiB */
static const uint64_t I128_JOB_VA = TEST_VA + 0xe000;
static const uint64_t I128_OUT_VA = TEST_VA + 0xf000;    /* 256 u32 (64 threads x 4) */
static const uint32_t N_THREADS = 256;  /* 4 workgroups of 64; in/out = 1 KiB each */
static const uint32_t MUL = 3, ADD = 7;

/* Build one job and write it as <prefix>_job[] / <prefix>_cs[] plus <PREFIX>_* defines. */
static bool emit_job(FILE *f, const char *prefix, const char *PREFIX, const mc::Kernel &k, uint64_t job_va,
    uint64_t out_va, uint32_t n_threads)
{
	mc::JobParams p = {};
	p.k = k;
	p.n_threads = n_threads;
	p.mul = MUL;
	p.add = ADD;
	p.in_va = IN_VA;
	p.out_va = out_va;

	mc::Layout l = mc::plan(p);
	if (l.cs_off > 0x1000 || l.total > 0x2000) {
		fprintf(stderr, "%s: layout too large: descriptors end at %u, total %u\n", prefix, l.cs_off, l.total);
		return false;
	}
	std::vector<uint8_t> buf(l.total);
	mc::Built b = {};
	if (!mc::emit_compute_stream(buf.data(), job_va, p, &b)) {
		fprintf(stderr, "%s: cs_builder failed\n", prefix);
		return false;
	}
	/* The stream lives past the job page in the builder's buffer; the kernel puts it in its ring. */
	const uint64_t *cs = (const uint64_t *)(buf.data() + l.cs_off);
	unsigned ncs = b.stream_size / 8;

	fprintf(f, "/* %s: job page at GPU VA 0x%llx (FAU @0x%x, code @0x%x, TSD @0x%x, SPD @0x%x), in[] at 0x%llx,\n"
	    " * out at 0x%llx; %u threads in %u workgroups of %u. */\n", prefix, (unsigned long long)job_va,
	    l.fau_off, l.code_off, l.tsd_off, l.spd_off, (unsigned long long)IN_VA, (unsigned long long)out_va,
	    n_threads, b.groups, k.wg_size);
	fprintf(f, "#define %s_JOB_VA       0x%llxu\n", PREFIX, (unsigned long long)job_va);
	fprintf(f, "#define %s_OUT_VA       0x%llxu\n", PREFIX, (unsigned long long)out_va);
	fprintf(f, "#define %s_CODE_OFF     0x%xu\n", PREFIX, l.code_off);
	fprintf(f, "#define %s_JOB_BYTES    %uu\n\n", PREFIX, l.cs_off);
	fprintf(f, "static const uint8_t %s_job[%u] = {", prefix, l.cs_off);
	for (unsigned i = 0; i < l.cs_off; i++) {
		fprintf(f, "%s0x%02x,", i % 16 ? " " : "\n\t", buf[i]);
	}
	fprintf(f, "\n};\n\n");
	fprintf(f, "static const uint64_t %s_cs[%u] = {", prefix, ncs);
	for (unsigned i = 0; i < ncs; i++) {
		fprintf(f, "\n\t0x%016llxULL,  /* opcode %llu */", (unsigned long long)cs[i],
		    (unsigned long long)(cs[i] >> 56));
	}
	fprintf(f, "\n};\n\n");
	printf("%s: job %u bytes, %u CS instructions, %u workgroups\n", prefix, l.cs_off, ncs, b.groups);
	return true;
}

int main(int argc, char **argv)
{
	if (argc != 2) {
		fprintf(stderr, "usage: %s OUT.h\n", argv[0]);
		return 2;
	}
	FILE *f = fopen(argv[1], "w");
	if (!f) {
		perror(argv[1]);
		return 1;
	}
	fprintf(f, "/* generated by tools/gpu/gen-husky-compute.cpp; do not edit */\n");
	fprintf(f, "/*\n * In-kernel compute jobs (huskygpu=4), CS words for the kernel's ring:\n"
	    " *   husky_comp   mul_add: out[i] = in[i] * %u + %u (xnu 0098)\n"
	    " *   husky_probe  imul_probe: five variants of that arithmetic, 1 KiB apart (xnu 0099)\n"
	    " *   husky_i128   i128_probe: out[i]=in[i] via LOAD.i128/STORE.i128, 64 threads x 4 u32 (xnu 0102)\n */\n",
	    MUL, ADD);
	fprintf(f, "#define HUSKY_COMP_IN_VA        0x%llxu\n", (unsigned long long)IN_VA);
	fprintf(f, "#define HUSKY_COMP_THREADS      %uu\n", N_THREADS);
	fprintf(f, "#define HUSKY_COMP_MUL          %uu\n", MUL);
	fprintf(f, "#define HUSKY_COMP_ADD          %uu\n\n", ADD);

	mc::Kernel mul_add = {mul_add_code, MUL_ADD_CODE_BYTES, MUL_ADD_PRELOAD_MASK, MUL_ADD_FAU_SLOTS,
	    MUL_ADD_WORK_REGS, MUL_ADD_THREADS_PER_GROUP};
	mc::Kernel probe = {imul_probe_code, IMUL_PROBE_CODE_BYTES, IMUL_PROBE_PRELOAD_MASK, IMUL_PROBE_FAU_SLOTS,
	    IMUL_PROBE_WORK_REGS, IMUL_PROBE_THREADS_PER_GROUP};
	mc::Kernel i128 = {i128_probe_code, I128_PROBE_CODE_BYTES, I128_PROBE_PRELOAD_MASK, I128_PROBE_FAU_SLOTS,
	    I128_PROBE_WORK_REGS, I128_PROBE_THREADS_PER_GROUP};
	bool ok = emit_job(f, "husky_comp", "HUSKY_COMP", mul_add, JOB_VA, OUT_VA, N_THREADS) &&
	    emit_job(f, "husky_probe", "HUSKY_PROBE", probe, PROBE_JOB_VA, PROBE_OUT_VA, N_THREADS) &&
	    emit_job(f, "husky_i128", "HUSKY_I128", i128, I128_JOB_VA, I128_OUT_VA, 64);
	fclose(f);
	return ok ? 0 : 1;
}

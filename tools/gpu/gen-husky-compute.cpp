/*
 * gen-husky-compute: build husky_gpu.c's in-kernel compute smoke job on the host and write it as a C
 * header (bsd/dev/husky_gpu_compute.h in the xnu clone).
 *
 *   gen-husky-compute OUT.h
 *
 * The kernel runs this job on CSG0/CS0 right after its store job (xnu 0098, huskygpu=4): one
 * GPU-executable page holds the FAU, the mul_add shader, the TSD and the SPD; the compute CS
 * instructions are appended to the kernel's ring. Everything sits at fixed GPU addresses in the
 * kernel's job area (husky_gpu.c TEST_VA), so the kernel only copies bytes. Mesa's genxml packers
 * and cs_builder (MIT, used as a library at build time) encode the descriptors and instructions;
 * mali_compute_build.h is the host-tested recipe (tests/host/test_compute_job).
 *
 * Build: see tools/gpu/Makefile (needs a Mesa checkout, MESA_SRC).
 */
#include "mali_compute_build.h"
#include "mul_add_kernel.h"

#include <cstdio>
#include <cstdlib>
#include <vector>

/* Must match husky_gpu.c: TEST_VA + COMP_JOB / COMP_IN / COMP_OUT. */
static const uint64_t TEST_VA = 0x06000000;
static const uint64_t JOB_VA = TEST_VA + 0x4000;
static const uint64_t IN_VA = TEST_VA + 0x5000;
static const uint64_t OUT_VA = TEST_VA + 0x6000;
static const uint32_t N_THREADS = 256;  /* 4 workgroups of 64; in/out = 1 KiB each */
static const uint32_t MUL = 3, ADD = 7;

int main(int argc, char **argv)
{
	if (argc != 2) {
		fprintf(stderr, "usage: %s OUT.h\n", argv[0]);
		return 2;
	}
	mc::JobParams p = {};
	p.k.code = mul_add_code;
	p.k.code_bytes = MUL_ADD_CODE_BYTES;
	p.k.preload_mask = MUL_ADD_PRELOAD_MASK;
	p.k.fau_slots = MUL_ADD_FAU_SLOTS;
	p.k.work_regs = MUL_ADD_WORK_REGS;
	p.k.wg_size = MUL_ADD_THREADS_PER_GROUP;
	p.n_threads = N_THREADS;
	p.mul = MUL;
	p.add = ADD;
	p.in_va = IN_VA;
	p.out_va = OUT_VA;

	mc::Layout l = mc::plan(p);
	if (l.cs_off > 0x1000 || l.total > 0x2000) {
		fprintf(stderr, "layout too large: descriptors end at %u, total %u\n", l.cs_off, l.total);
		return 1;
	}
	std::vector<uint8_t> buf(l.total);
	mc::Built b = {};
	if (!mc::emit_compute_stream(buf.data(), JOB_VA, p, &b)) {
		fprintf(stderr, "cs_builder failed\n");
		return 1;
	}
	/* The stream lives past the job page in the builder's buffer; the kernel puts it in its ring. */
	const uint64_t *cs = (const uint64_t *)(buf.data() + l.cs_off);
	unsigned ncs = b.stream_size / 8;

	FILE *f = fopen(argv[1], "w");
	if (!f) {
		perror(argv[1]);
		return 1;
	}
	fprintf(f, "/* generated by tools/gpu/gen-husky-compute.cpp; do not edit */\n");
	fprintf(f, "/*\n * In-kernel compute smoke job (xnu 0098, huskygpu=4): out[i] = in[i] * %u + %u for\n"
	    " * i < %u, %u workgroups of %u threads. Job page at GPU VA 0x%llx (FAU @0x%x, mul_add code @0x%x,\n"
	    " * TSD @0x%x, SPD @0x%x), in[] at 0x%llx, out[] at 0x%llx. The CS words go in the ring.\n */\n",
	    MUL, ADD, N_THREADS, b.groups, p.k.wg_size, (unsigned long long)JOB_VA, l.fau_off, l.code_off,
	    l.tsd_off, l.spd_off, (unsigned long long)IN_VA, (unsigned long long)OUT_VA);
	fprintf(f, "#define HUSKY_COMP_JOB_VA       0x%llxu\n", (unsigned long long)JOB_VA);
	fprintf(f, "#define HUSKY_COMP_IN_VA        0x%llxu\n", (unsigned long long)IN_VA);
	fprintf(f, "#define HUSKY_COMP_OUT_VA       0x%llxu\n", (unsigned long long)OUT_VA);
	fprintf(f, "#define HUSKY_COMP_THREADS      %uu\n", N_THREADS);
	fprintf(f, "#define HUSKY_COMP_MUL          %uu\n", MUL);
	fprintf(f, "#define HUSKY_COMP_ADD          %uu\n", ADD);
	fprintf(f, "#define HUSKY_COMP_CODE_OFF     0x%xu\n", l.code_off);
	fprintf(f, "#define HUSKY_COMP_JOB_BYTES    %uu\n\n", l.cs_off);
	fprintf(f, "static const uint8_t husky_comp_job[%u] = {", l.cs_off);
	for (unsigned i = 0; i < l.cs_off; i++) {
		fprintf(f, "%s0x%02x,", i % 16 ? " " : "\n\t", buf[i]);
	}
	fprintf(f, "\n};\n\n");
	fprintf(f, "static const uint64_t husky_comp_cs[%u] = {", ncs);
	for (unsigned i = 0; i < ncs; i++) {
		fprintf(f, "\n\t0x%016llxULL,  /* opcode %llu */", (unsigned long long)cs[i],
		    (unsigned long long)(cs[i] >> 56));
	}
	fprintf(f, "\n};\n");
	fclose(f);
	printf("%s: job %u bytes, %u CS instructions, %u workgroups\n", argv[1], l.cs_off, ncs, b.groups);
	return 0;
}

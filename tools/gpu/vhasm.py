"""
vhasm.py - assemble a Valhall (arch 11) assembly file into a C header.

Intended repo path: tests/tools/vhasm.py

Uses Mesa's valhall/asm.py as a LIBRARY (parse_asm(line) -> 64-bit instruction word); the
instruction syntax is Mesa's, the programs are ours.  Directives start with "#!":
    #! name <ident>            C identifier prefix (default: file stem)
    #! preload r60 r61 ...     registers preloaded by the hardware (SPD preload mask, r48..r63 only)
    #! fau_slots <n>           64-bit FAU slots the kernel reads (FAU register bits 63:56)
    #! work_regs <32|64>       registers per thread to request in the SPD
    #! threads_per_group <n>   workgroup size the test dispatches
Other lines starting with '#' are comments; a ';' starts a trailing comment.

Output (C, usable from C++):
    static const uint64_t <name>_code[N];   one word per instruction, little-endian in memory
    #define <NAME>_NUM_INSTR / _CODE_BYTES / _PRELOAD_MASK / _FAU_SLOTS / _WORK_REGS / _THREADS_PER_GROUP
    static const char *const <name>_src[N]; the assembly text of each instruction (for logging)
"""
import argparse
import os
import re
import sys


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--valhall-dir', required=True, help='Mesa src/panfrost/compiler/bifrost/valhall')
    ap.add_argument('--name')
    ap.add_argument('-o', '--output', required=True)
    ap.add_argument('input')
    a = ap.parse_args()

    sys.path.insert(0, a.valhall_dir)
    import asm  # noqa: E402  (Mesa; needs ISA.xml next to it)

    name = a.name
    preload = 0
    fau_slots = 0
    work_regs = 64
    threads = 64
    insts = []
    for lineno, raw in enumerate(open(a.input), 1):
        line = raw.strip()
        if line.startswith('#!'):
            toks = line[2:].split()
            key, vals = toks[0], toks[1:]
            if key == 'name':
                name = vals[0]
            elif key == 'preload':
                for r in vals:
                    n = int(r.lstrip('r'))
                    if not 48 <= n <= 63:
                        sys.exit('%s:%d: only r48..r63 can be preloaded' % (a.input, lineno))
                    preload |= 1 << n
            elif key == 'fau_slots':
                fau_slots = int(vals[0])
            elif key == 'work_regs':
                work_regs = int(vals[0])
                if work_regs not in (32, 64):
                    sys.exit('%s:%d: work_regs must be 32 or 64' % (a.input, lineno))
            elif key == 'threads_per_group':
                threads = int(vals[0])
            else:
                sys.exit('%s:%d: unknown directive %s' % (a.input, lineno, key))
            continue
        if not line or line.startswith('#'):
            continue
        line = re.sub(r'\s*;.*$', '', line)
        try:
            word = asm.parse_asm(line)
        except asm.ParseError as e:
            sys.exit('%s:%d: %s: %s' % (a.input, lineno, line, e.error))
        insts.append((word, line))
    name = name or os.path.splitext(os.path.basename(a.input))[0]
    if not insts:
        sys.exit('no instructions')
    if not insts[-1][1].split()[0].split('.')[-1] == 'end' and '.end' not in insts[-1][1].split()[0]:
        sys.exit('last instruction must carry the .end modifier (thread termination)')
    up = re.sub(r'\W', '_', name).upper()
    lo = re.sub(r'\W', '_', name)
    with open(a.output, 'w') as f:
        f.write('/* generated by tests/tools/vhasm.py from %s; do not edit */\n' % os.path.basename(a.input))
        f.write('#include <stdint.h>\n')
        f.write('#define %s_NUM_INSTR %d\n#define %s_CODE_BYTES %d\n' % (up, len(insts), up, 8 * len(insts)))
        f.write('#define %s_PRELOAD_MASK 0x%016xull\n' % (up, preload))
        f.write('#define %s_FAU_SLOTS %d\n#define %s_WORK_REGS %d\n#define %s_THREADS_PER_GROUP %d\n' % (
            up, fau_slots, up, work_regs, up, threads))
        f.write('static const uint64_t %s_code[%d] = {\n' % (lo, len(insts)))
        for w, l in insts:
            f.write('    0x%016xull, /* %s */\n' % (w, l))
        f.write('};\n')
        f.write('static const char *const %s_src[%d] = {\n' % (lo, len(insts)))
        for w, l in insts:
            f.write('    "%s",\n' % l.replace('"', '\\"'))
        f.write('};\n')


if __name__ == '__main__':
    main()
